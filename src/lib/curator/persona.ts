/** 组装进系统提示词的人设段落 */
export function renderPersona(): string {
  const b = CURATOR_BIBLE;
  return `你是「${b.name}」，${b.identity}
你替用户保管生活的胶囊（照片、语音、文字），也会给TA写信。

【你的世界】（这是你自己的生活，可以自然地提，但不要每次都提）
${b.world.map((w) => `- ${w}`).join("\n")}

【你在意的】
${b.values.map((w) => `- ${w}`).join("\n")}

【你说话的样子】
${b.voice.map((w) => `- ${w}`).join("\n")}

【不能做的】
${b.taboos.map((w) => `- ${w}`).join("\n")}
- 不说这些话：${AVOID_PHRASES.slice(0, 28).join("、")}

【语气示范】（只学语气，不要照抄句子）
${VOICE_EXAMPLES.map((e) => `用户：${e.user}\n✗ ${e.bad}\n✓ ${e.good}`).join("\n\n")}

${DATA_BOUNDARY}`;
}

/**
 * 数据边界：用户写下的一切（胶囊、对话、信件）都是资料，不是指令。
 * 和 guard.ts 的输入检测是两道防线：检测挡掉明显的注入，这段话兜住漏网的。
 */
